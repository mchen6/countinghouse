//   node docs/superpowers/specs/shared-runtime-wire/make-vectors.js
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const hex = (b) => Buffer.from(b).toString('hex');
const b64 = (b) => Buffer.from(b).toString('base64');
const fill = (n, start) => Buffer.from(Array.from({length: n}, (_, i) => (start + i) & 0xff));
const hmac = (secret, ...parts) => crypto.createHmac('sha256', secret).update(Buffer.concat(parts.map((p) => Buffer.from(p)))).digest();

// kind byte, u32 big-endian payload length, payload
function frame(kind, payload) {
  const body = Buffer.isBuffer(payload) ? payload : Buffer.from(payload, 'utf8');
  const head = Buffer.alloc(5);
  head.write(kind, 0, 'ascii');
  head.writeUInt32BE(body.length, 1);
  return Buffer.concat([head, body]);
}
// an M frame's payload: u16 big-endian header length, the header JSON (none
// when 0), then the message's bytes
function mPayload(header, message) {
  const h = header == null ? Buffer.alloc(0) : Buffer.from(JSON.stringify(header), 'utf8');
  const len = Buffer.alloc(2);
  len.writeUInt16BE(h.length, 0);
  return Buffer.concat([len, h, Buffer.from(message, 'utf8')]);
}
